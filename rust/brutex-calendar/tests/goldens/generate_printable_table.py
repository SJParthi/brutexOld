#!/usr/bin/env python3
# ruff: noqa: S101, T201, PLR2004 — dev-tooling generator (the
# generate_goldens.py conventions): asserts + prints are the interface, and
# the Unicode plane bounds (0x110000, the surrogate block) are the domain
# constants themselves, not magic values.
"""Generate `src/py_printable_15_0.rs` — the exact CPython printability table
(DEC-RUST-CALENDAR-LEAVES-001, refuter finding F1).

CPython 3.12's `repr(str)` escapes a char iff it is NOT
``str.isprintable()``-printable (general categories Cc/Cf/Cs/Co/Cn/Zl/Zp/Zs,
with U+0020 exempt).  The crate originally consulted the `unicode-properties`
Rust crate, whose tables track a NEWER Unicode than the CPython 3.12 baseline
(Unicode 15.0.0) — every codepoint assigned after 15.0 diverged (raw char in
Rust vs `\\U...` escape in Python; the refuter enumerated 400+).

Root-cause fix: this script asks the golden-generator interpreter ITSELF —
the SAME `.venv` CPython 3.12 that generates `tests/goldens/*.json` — for
``chr(cp).isprintable()`` over the whole plane and emits a static, sorted,
inclusive range table as GENERATED Rust source.  Printability is thereby
pinned to the goldens' exact Unicode version by construction.

Surrogates (U+D800..U+DFFF) are EXCLUDED from the table: a Rust `char` cannot
hold a lone surrogate, so `py_str_repr` can never be asked about one — a
lone-surrogate `\\udXXX` escape in the source JSON makes serde_json refuse
the parse and the FFI binding ABSTAINS to the Python oracle (the documented
contract; unchanged by this fix).

Run from the repo root with the project venv's Python 3.12:

    .venv/bin/python rust/brutex-calendar/tests/goldens/generate_printable_table.py

Regenerate (and review the diff) only when the golden-generator interpreter's
Unicode baseline moves — i.e. together with a full golden regeneration on the
new CPython baseline, never alone.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / "src" / "py_printable_15_0.rs"

assert sys.version_info[:2] == (3, 12), "the table must come from the CPython 3.12 baseline"

EXPECTED_UNIDATA = "15.0.0"
assert unicodedata.unidata_version == EXPECTED_UNIDATA, (
    f"interpreter Unicode {unicodedata.unidata_version} != the pinned {EXPECTED_UNIDATA}; "
    "a new baseline needs a renamed table module + a full golden regeneration"
)


def printable_ranges() -> list[tuple[int, int]]:
    """Sorted inclusive (lo, hi) ranges where ``chr(cp).isprintable()`` is True."""
    ranges: list[tuple[int, int]] = []
    start: int | None = None
    for cp in range(0x110000 + 1):  # one past the plane: flushes the last run
        printable = (
            cp < 0x110000
            and not (0xD800 <= cp <= 0xDFFF)  # surrogates: unreachable from Rust `char`
            and chr(cp).isprintable()
        )
        if printable and start is None:
            start = cp
        elif not printable and start is not None:
            ranges.append((start, cp - 1))
            start = None
    return ranges


def main() -> None:
    ranges = printable_ranges()
    count = sum(hi - lo + 1 for lo, hi in ranges)
    lines = [
        "//! GENERATED by tests/goldens/generate_printable_table.py — DO NOT EDIT.",
        "//!",
        "//! CPython `str.isprintable()` truth table, emitted by the golden-generator",
        f"//! interpreter itself (CPython {sys.version.split()[0]}, unicodedata",
        f"//! {unicodedata.unidata_version}) so `py_str_repr`'s escape decision is pinned to",
        "//! the goldens' exact Unicode version by construction",
        "//! (DEC-RUST-CALENDAR-LEAVES-001, refuter finding F1).",
        "//!",
        "//! Surrogates (U+D800..U+DFFF) are excluded: a Rust `char` cannot hold a",
        "//! lone surrogate — such input makes serde_json refuse the parse and the",
        "//! FFI binding abstains to the Python oracle before repr is ever asked.",
        "",
        f"/// Inclusive `(lo, hi)` codepoint ranges ({len(ranges)} ranges, {count} codepoints)",
        "/// for which CPython 3.12 `str.isprintable()` is `True` (Unicode 15.0.0),",
        "/// sorted ascending and non-overlapping. U+0020 (the exempt ASCII space)",
        "/// is baked in as printable, so consumers need no special case.",
        "#[rustfmt::skip]",
        "pub(crate) static PY_PRINTABLE_RANGES_15_0: &[(u32, u32)] = &[",
    ]
    lines.extend(f"    (0x{lo:x}, 0x{hi:x})," for lo, hi in ranges)
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}: {len(ranges)} ranges, {count} printable codepoints")


if __name__ == "__main__":
    main()
