"""Property tests for the Greeks enrichment (DEC-GREEKS-ENGINE-PR2B-001).

No-arbitrage monotonicities asserted on the STORED overlay values the pure
core emits (plan §15 test obligation), the IV round-trip against a
kernel-generated premium, and the lossless provenance pack/unpack inverse.
"""

from __future__ import annotations

import math
from datetime import UTC, datetime
from decimal import Decimal
from itertools import pairwise

import pytest
from hypothesis import given, settings
from hypothesis import strategies as st

pytest.importorskip("trading_core", reason="greeks enrichment needs the trading_core wheel")

from brutex.data.fno_symbol import parse_fno_symbol
from brutex.data.greeks_enrich import (
    DEGENERATE_TIME_VALUE_REL,
    STATUS_BELOW_INTRINSIC,
    STATUS_OK,
    enrich_option_bars,
    expiry_instant_utc,
    pack_greeks_provenance,
    t_years_act365,
    unpack_greeks_provenance,
)
from brutex.data.models import GREEKS_OVERLAY_FIELDS, FnoGreeksBar
from brutex.options.greeks import compute_greeks
from brutex.options.risk_free import FixedRateSource

_SPOT = Decimal("21500")
_TS = datetime(2024, 1, 15, 3, 45, tzinfo=UTC)  # ten days to the 25Jan24 expiry
_RATE = FixedRateSource()
_STRIKE_GRID = st.integers(min_value=400, max_value=460).map(lambda k: k * 50)  # 20000..23000


def _kernel_premium(strike: int, sigma: float, *, is_call: bool) -> float:
    """A premium GENERATED by the shared kernel at a known sigma (always solvable)."""
    rate = _RATE.rate_on(_TS.date())
    parts = parse_fno_symbol(_ce(strike))
    assert parts is not None
    t = t_years_act365(_TS, expiry_instant_utc(parts.expiry))
    result = compute_greeks(
        sigma=sigma,
        forward=float(_SPOT) * math.exp(rate.rate * t),
        strike=float(strike),
        t_years=t,
        rate=rate,
        is_call=is_call,
    )
    assert result is not None
    return result.price


def _ce(strike: int) -> str:
    return f"NSE-NIFTY-25Jan24-{strike}-CE"


def _pe(strike: int) -> str:
    return f"NSE-NIFTY-25Jan24-{strike}-PE"


def _enrich(symbol: str, premium: float) -> FnoGreeksBar:
    row: dict[str, object] = {
        "timestamp": _TS,
        "open": premium,
        "high": premium,
        "low": premium,
        "close": premium,
        "volume": 1,
        "open_interest": 1,
    }
    for name in GREEKS_OVERLAY_FIELDS:
        row[name] = None
    parts = parse_fno_symbol(symbol)
    assert parts is not None
    bars, _stats = enrich_option_bars(
        [row],
        parts=parts,
        spot_by_ts={_TS: _SPOT},
        rate_source=_RATE,
        style_flag=1,
    )
    return bars[0]


class TestProvenanceRoundTrip:
    @given(
        formula=st.integers(min_value=0, max_value=255),
        rate_source=st.integers(min_value=0, max_value=15),
        rate_version=st.integers(min_value=0, max_value=15),
        q_bias=st.integers(min_value=0, max_value=3),
        tte=st.integers(min_value=0, max_value=3),
        style=st.integers(min_value=0, max_value=7),
        status=st.integers(min_value=0, max_value=15),
    )
    def test_pack_unpack_is_lossless(
        self,
        formula: int,
        rate_source: int,
        rate_version: int,
        q_bias: int,
        tte: int,
        style: int,
        status: int,
    ) -> None:
        pid = pack_greeks_provenance(
            rate_source_id=rate_source,
            rate_version=rate_version,
            style_flag=style,
            status=status,
            formula_version=formula,
            q_bias_id=q_bias,
            tte_convention_id=tte,
        )
        assert 0 <= pid < 2**31  # always Int32-storable
        fields = unpack_greeks_provenance(pid)
        assert (
            fields.formula_version,
            fields.rate_source_id,
            fields.rate_version,
            fields.q_bias_id,
            fields.tte_convention_id,
            fields.style_flag,
            fields.status,
        ) == (formula, rate_source, rate_version, q_bias, tte, style, status)


class TestStoredNoArbProperties:
    """No-arb shape of the STORED overlay across a kernel-priced strike ladder."""

    @settings(max_examples=25, deadline=None)
    @given(sigma=st.floats(min_value=0.08, max_value=0.6), strike=_STRIKE_GRID)
    def test_iv_round_trip_recovers_sigma(self, sigma: float, strike: int) -> None:
        premium = _kernel_premium(strike, sigma, is_call=True)
        bar = _enrich(_ce(strike), premium)
        pid = bar.greeks_provenance_id
        assert pid is not None
        rate = _RATE.rate_on(_TS.date())
        parts = parse_fno_symbol(_ce(strike))
        assert parts is not None
        t = t_years_act365(_TS, expiry_instant_utc(parts.expiry))
        floor = max(0.0, float(_SPOT) - strike * math.exp(-rate.rate * t))
        if premium <= floor + DEGENERATE_TIME_VALUE_REL * premium:
            # ~zero time value (deep-ITM at low sigma): sigma is NOT
            # recoverable from the premium — any sigma across a wide band
            # reprices it within the kernel's verification tolerance, so the
            # enrichment honestly refuses instead of storing an arbitrary
            # root (DEC-GREEKS-CORRECTNESS-AUDIT-001 IVX-1; the pre-fix pin
            # asserted STATUS_OK here, i.e. the artifact itself).
            assert unpack_greeks_provenance(pid).status == STATUS_BELOW_INTRINSIC
            assert bar.iv is None
        else:
            assert unpack_greeks_provenance(pid).status == STATUS_OK
            assert bar.iv is not None
            # The stored IV reprices the kernel-generated premium — the
            # kernel's own 1e-9 verification bound, relaxed only for the
            # premium's f64 quantization.
            assert bar.iv == pytest.approx(sigma, rel=5e-6, abs=5e-7)

    @settings(max_examples=15, deadline=None)
    @given(sigma=st.floats(min_value=0.1, max_value=0.5))
    def test_call_delta_monotone_decreasing_in_strike(self, sigma: float) -> None:
        strikes = [20000, 20500, 21000, 21500, 22000, 22500, 23000]
        deltas = []
        for strike in strikes:
            bar = _enrich(_ce(strike), _kernel_premium(strike, sigma, is_call=True))
            assert bar.delta is not None
            assert 0.0 <= bar.delta <= 1.0
            deltas.append(bar.delta)
        assert all(a >= b for a, b in pairwise(deltas))

    @settings(max_examples=15, deadline=None)
    @given(sigma=st.floats(min_value=0.1, max_value=0.5))
    def test_put_delta_monotone_decreasing_in_strike(self, sigma: float) -> None:
        strikes = [20000, 20500, 21000, 21500, 22000, 22500, 23000]
        deltas = []
        for strike in strikes:
            bar = _enrich(_pe(strike), _kernel_premium(strike, sigma, is_call=False))
            assert bar.delta is not None
            assert -1.0 <= bar.delta <= 0.0
            deltas.append(bar.delta)
        # A higher-strike put is deeper ITM → its delta is MORE negative.
        assert all(a >= b for a, b in pairwise(deltas))

    @settings(max_examples=15, deadline=None)
    @given(sigma=st.floats(min_value=0.1, max_value=0.5), strike=_STRIKE_GRID)
    def test_gamma_and_vega_non_negative(self, sigma: float, strike: int) -> None:
        bar = _enrich(_ce(strike), _kernel_premium(strike, sigma, is_call=True))
        assert bar.gamma is not None and bar.gamma >= 0.0
        assert bar.vega is not None and bar.vega >= 0.0

    @settings(max_examples=15, deadline=None)
    @given(sigma=st.floats(min_value=0.1, max_value=0.5), strike=_STRIKE_GRID)
    def test_side_symmetric_gamma(self, sigma: float, strike: int) -> None:
        """CE and PE at the same coordinates share one gamma (Black-76 identity)."""
        ce = _enrich(_ce(strike), _kernel_premium(strike, sigma, is_call=True))
        pe = _enrich(_pe(strike), _kernel_premium(strike, sigma, is_call=False))
        assert ce.gamma is not None and pe.gamma is not None
        assert ce.gamma == pytest.approx(pe.gamma, rel=1e-6)
