"""End-to-end CLI proof of the resume store guard wiring (DEC-SWEEP-RESUME-STORE-GUARD-001, T17).

``cmd_sweep_all`` is ``# pragma: no cover`` (an orchestration shim over the
100%-tested engine), so — exactly like ``test_cli_results_depth_wiring.py``,
the precedent suite — this is the HONEST functional validation of the guard's
production wiring: a tiny REAL lake is persisted with the same writers ingest
uses and ``cli.cmd_sweep_all`` is driven for real, proving

* SEQUENTIAL arm (``BRUTEX_SWEEP_WORKERS=1``): a deleted tuple store Parquet
  is regenerated byte-identically by the second invocation — the
  ``make_store_for`` → ``TupleStoreProvider`` auto-activation reaches the
  supervisor with ZERO call-site changes (a severed ``.store_path`` /
  dropped provider refactor fails this test);
* PARALLEL arm (``BRUTEX_SWEEP_WORKERS=2`` — the production default shape):
  the same recovery through ``run_parallel_grid``'s gated tiers;
* a JUNK ``BRUTEX_SWEEP_RESUME_STORE_GUARD`` is a clean PRE-sweep
  ``EXIT_USER_ERROR`` (the eager CLI resolution — nothing runs).
"""

from __future__ import annotations

from datetime import UTC, datetime, timedelta, timezone
from decimal import Decimal
from pathlib import Path
from typing import Any

import pytest
from brutex import cli
from brutex.data.catalog import Catalog
from brutex.data.models import CandleBar
from brutex.data.parquet_writer import ParquetWriter
from brutex.data.sink import ParquetBarSink

pytest.importorskip("polars")
pytest.importorskip("duckdb")
pytest.importorskip("pyarrow")
pytest.importorskip("lmdb")

_IST = timezone(timedelta(hours=5, minutes=30))
_EXCHANGE = "NSE"
_SEGMENT = "INDEX"
_SYMBOL = "NIFTY"
_INTERVAL = "1minute"


def _bars() -> list[CandleBar]:
    """A short in-session NIFTY minute window (stored UTC), valid OHLC."""
    out: list[CandleBar] = []
    for i in range(8):
        ts = datetime(2024, 1, 2, 9, 16 + i, tzinfo=_IST).astimezone(UTC)
        out.append(
            CandleBar(
                timestamp=ts,
                open=Decimal("100.00"),
                high=Decimal("102.00"),
                low=Decimal("99.00"),
                close=Decimal("100.00") + Decimal(i) / 10,
                volume=1000,
                open_interest=None,
            )
        )
    return out


def _persist(tmp_path: Path) -> tuple[Path, Path]:
    lake_root = tmp_path / "lake"
    catalog_path = tmp_path / "catalog.duckdb"
    writer = ParquetWriter(lake_root=lake_root)
    with Catalog.open(catalog_path) as cat:
        sink = ParquetBarSink(writer=writer, catalog=cat)
        sink.append(
            exchange=_EXCHANGE,
            segment=_SEGMENT,
            symbol=_SYMBOL,
            interval=_INTERVAL,
            bars=_bars(),
        )
    return lake_root, catalog_path


def _sweep_all(lake_root: Path, catalog_path: Path, results_root: Path, **overrides: Any) -> int:
    kwargs: dict[str, Any] = {
        "lake_root": lake_root,
        "catalog_path": catalog_path,
        "results_root": results_root,
        "exchange": _EXCHANGE,
        "segment": _SEGMENT,
        "symbols": _SYMBOL,
        "intervals": _INTERVAL,
        "start": "2024-01-02",
        "end": "2024-01-03",
        "directions": "BUY",
        "k": "2",
        "conditions": "0,1,2,3",
        "sl": "none",
        "tp": "none",
        "top": 10,
        "mode": "A",
        "max_tuples": None,
        "max_combos": None,
        "data_snapshot_hash": None,
        "options_sim": False,
    }
    kwargs.update(overrides)
    return cli.cmd_sweep_all(**kwargs)


def _tuple_stores(results_root: Path) -> list[Path]:
    """The per-tuple store Parquets (sweep tree only — depth sidecars excluded)."""
    return sorted(
        p
        for p in results_root.rglob("*.parquet")
        if not p.name.endswith((".trades.parquet", ".aggs.parquet", ".equity.parquet"))
    )


@pytest.fixture(autouse=True)
def _no_guard_env(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.delenv("BRUTEX_SWEEP_RESUME_STORE_GUARD", raising=False)
    monkeypatch.delenv("BRUTEX_RESULTS_DEPTH", raising=False)


@pytest.mark.parametrize("workers", ["1", "2"])
def test_deleted_tuple_store_regenerates_on_the_second_invocation(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, workers: str
) -> None:
    """T17 — BOTH CLI arms: run 1 completes, one tuple store is deleted, run 2
    regenerates it byte-identically (exit 0 both times). The sequential arm
    pins the provider auto-activation; the parallel arm pins the
    production-default driver's gated tiers."""
    monkeypatch.setenv("BRUTEX_SWEEP_WORKERS", workers)
    lake_root, catalog_path = _persist(tmp_path)
    results_root = tmp_path / "sweeps"

    assert _sweep_all(lake_root, catalog_path, results_root) == 0
    stores = _tuple_stores(results_root)
    assert stores, "run 1 must persist at least one tuple store"
    victim = stores[0]
    snapshot = victim.read_bytes()
    victim.unlink()

    assert _sweep_all(lake_root, catalog_path, results_root) == 0
    assert victim.exists(), "the deleted tuple store must be regenerated (S5b)"
    assert victim.read_bytes() == snapshot


def test_junk_guard_env_is_a_clean_pre_sweep_user_error(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    """T10 (CLI arm) — junk BRUTEX_SWEEP_RESUME_STORE_GUARD exits
    EXIT_USER_ERROR before any compute (no results tree is created)."""
    monkeypatch.setenv("BRUTEX_SWEEP_WORKERS", "1")
    monkeypatch.setenv("BRUTEX_SWEEP_RESUME_STORE_GUARD", "maybe")
    lake_root, catalog_path = _persist(tmp_path)
    results_root = tmp_path / "sweeps"

    rc = _sweep_all(lake_root, catalog_path, results_root)
    assert rc == cli.EXIT_USER_ERROR
    err = capsys.readouterr().err
    assert "BRUTEX_SWEEP_RESUME_STORE_GUARD" in err
    assert not _tuple_stores(results_root) if results_root.exists() else True
