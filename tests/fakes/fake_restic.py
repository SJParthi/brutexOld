"""A REAL executable fake-restic stub, driven by a JSON script file.

DEC-BACKUP-OFFBOX-001 test plan (§14): the stub is written to disk as an
actual ``#!<python>`` executable and invoked through the REAL
:class:`brutex.backup.restic_runner.ResticRunner` default subprocess seam, so
the tests exercise argv building, child-env hygiene, stream capture and the
timeout/missing-binary mapping against a genuine child process — never a
monkeypatched ``subprocess``.

Behaviour is scripted per VERB KEY via a JSON config file the test writes
(:meth:`FakeRestic.set_script`); every invocation appends its argv to a call
log (:meth:`FakeRestic.calls`). Supported side effects (all applied by the
child process itself):

* ``restore`` default — copies each ``--include`` path's LIVE bytes under
  ``--target`` (the restic path-preserving layout);
* ``extra_writes`` — materialise snapshot-only files (live-missing cases);
* ``corrupt`` — flip the restored copy's last byte (the byte-mismatch
  negative — F20);
* ``truncate`` — drop the restored copy's tail (the audit PREFIX-law
  positive: a restored prefix of the live JSONL);
* ``skip_copy`` — restore succeeds (rc 0) but writes nothing;
* ``sleep`` — wedge the child (the F17a timeout negative);
* ``require_empty_stdin`` — exit non-zero unless stdin is at EOF (proves
  ``stdin=subprocess.DEVNULL``);
* ``dump_env`` — print the child's env as JSON (child-env hygiene proof).

Verb keys: ``cat-config`` / ``init`` / ``unlock`` / ``backup`` / ``forget`` /
``forget-snapshot`` (a 2-arg ``forget <id>``) / ``check`` / ``check-data``
(a ``check --read-data-subset=…``, falling back to ``check``) / ``snapshots``
/ ``ls`` / ``restore``. A key may map to a LIST of entries consumed by
occurrence (the call log is the durable per-process counter).
"""

from __future__ import annotations

import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

_STUB_TEMPLATE = '''#!{python}
"""Fake restic — generated by tests/fakes/fake_restic.py; JSON-scripted."""
import json
import os
import shutil
import sys

CONFIG = {config_path!r}
CALL_LOG = {call_log_path!r}


def _key(argv):
    verb = argv[0] if argv else ""
    if verb == "cat":
        return "cat-config"
    if verb == "forget" and len(argv) == 2:
        return "forget-snapshot"
    if verb == "check" and any(a.startswith("--read-data-subset") for a in argv):
        return "check-data"
    return verb


def _entry(cfg, key, occurrence):
    raw = cfg.get(key)
    if raw is None and key == "check-data":
        raw = cfg.get("check")
    if raw is None:
        return {{}}
    if isinstance(raw, list):
        return raw[min(occurrence, len(raw) - 1)]
    return raw


def _default_stdout(key):
    if key == "backup":
        return json.dumps({{"message_type": "summary", "snapshot_id": "fakesnap01"}}) + "\\n"
    if key == "snapshots":
        return "[]"
    return ""


def _do_restore(argv, entry):
    target = argv[argv.index("--target") + 1]
    includes = [argv[i + 1] for i, a in enumerate(argv) if a == "--include"]
    extra = entry.get("extra_writes", {{}})
    for path in includes:
        dest = os.path.join(target, path.lstrip("/"))
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        if path in extra:
            with open(dest, "w", encoding="utf-8") as handle:
                handle.write(extra[path])
        elif os.path.exists(path):
            shutil.copy2(path, dest)
    for path in entry.get("corrupt", []):
        dest = os.path.join(target, path.lstrip("/"))
        with open(dest, "rb") as handle:
            data = bytearray(handle.read())
        data[-1] ^= 0xFF
        with open(dest, "wb") as handle:
            handle.write(bytes(data))
    for path in entry.get("truncate", []):
        dest = os.path.join(target, path.lstrip("/"))
        with open(dest, "rb") as handle:
            data = handle.read()
        with open(dest, "wb") as handle:
            handle.write(data[: len(data) // 2])


def main():
    argv = sys.argv[1:]
    key = _key(argv)
    prior = 0
    if os.path.exists(CALL_LOG):
        with open(CALL_LOG, encoding="utf-8") as handle:
            for line in handle:
                if line.strip() and _key(json.loads(line)) == key:
                    prior += 1
    with open(CALL_LOG, "a", encoding="utf-8") as handle:
        handle.write(json.dumps(argv) + "\\n")
    cfg = {{}}
    if os.path.exists(CONFIG):
        with open(CONFIG, encoding="utf-8") as handle:
            cfg = json.load(handle)
    entry = _entry(cfg, key, prior)
    if entry.get("sleep"):
        import time

        time.sleep(float(entry["sleep"]))
    if entry.get("require_empty_stdin") and sys.stdin.read() != "":
        sys.exit(7)
    if entry.get("dump_env"):
        sys.stdout.write(json.dumps(dict(os.environ)))
        sys.exit(int(entry.get("exit", 0)))
    if key == "restore" and int(entry.get("exit", 0)) == 0 and not entry.get("skip_copy"):
        _do_restore(argv, entry)
    sys.stdout.write(entry.get("stdout", _default_stdout(key)))
    sys.stderr.write(entry.get("stderr", ""))
    sys.exit(int(entry.get("exit", 0)))


if __name__ == "__main__":
    main()
'''


@dataclass(frozen=True, slots=True)
class FakeRestic:
    """Handle to one on-disk fake-restic executable + its script/log files."""

    binary: Path
    config_path: Path
    call_log_path: Path

    def set_script(self, script: dict[str, Any]) -> None:
        """(Re)write the JSON behaviour script (re-read on EVERY invocation)."""
        self.config_path.write_text(json.dumps(script), encoding="utf-8")

    def calls(self) -> list[list[str]]:
        """Return every recorded invocation's argv (oldest first)."""
        if not self.call_log_path.exists():
            return []
        return [
            json.loads(line)
            for line in self.call_log_path.read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]

    def verbs(self) -> list[str]:
        """Return the recorded verb (first argv token) sequence."""
        return [argv[0] if argv else "" for argv in self.calls()]

    def clear_calls(self) -> None:
        """Truncate the call log (fresh occurrence counting)."""
        self.call_log_path.write_text("", encoding="utf-8")


def write_fake_restic(bin_dir: Path, script: dict[str, Any] | None = None) -> FakeRestic:
    """Write a REAL executable fake-restic under *bin_dir* and return its handle.

    Parameters
    ----------
    bin_dir
        Directory (created if needed) for the executable + sidecar files.
    script
        Optional initial behaviour script (default: all verbs succeed with
        sensible default stdout).
    """
    bin_dir.mkdir(parents=True, exist_ok=True)
    config_path = bin_dir / "fake_restic_script.json"
    call_log_path = bin_dir / "fake_restic_calls.jsonl"
    binary = bin_dir / "restic"
    binary.write_text(
        _STUB_TEMPLATE.format(
            python=sys.executable,
            config_path=str(config_path),
            call_log_path=str(call_log_path),
        ),
        encoding="utf-8",
    )
    binary.chmod(0o755)
    config_path.write_text(json.dumps(script or {}), encoding="utf-8")
    call_log_path.write_text("", encoding="utf-8")
    return FakeRestic(binary=binary, config_path=config_path, call_log_path=call_log_path)
