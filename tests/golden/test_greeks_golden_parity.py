"""Greeks golden parity — the Python side of the bit-identity contract.

DEC-GREEKS-ENGINE-PR2-001 (plan `docs/GREEKS_ENGINE_PLAN.md` §10/§12,
ADR-0015 D6). Reads the SAME frozen fixture the Rust golden reads
(`tests/golden/fixtures/greeks_golden.json`, generated by
`tests/golden/generate_greeks_golden.py` — mpmath 50-digit references +
kernel-frozen bit patterns) and asserts, per case and per solve/sigma path:

1. **EXACT frozen bit-identity** through the compiled wheel — the fixture's
   bits were frozen FROM this artifact (the one BruteX production consumes),
   so this side is strict ``==`` on the 64-bit patterns. Together with the
   Rust golden (same fixture, documented ≤ 4-ULP link-product envelope) this
   is the Rust↔Python contract.
2. **Independent mpmath oracle** within the fixture's documented tolerance —
   the cross-platform contract (plan §13 open decision #6).
3. The `brutex.options.greeks` WRAPPER reproduces the same frozen bits
   end-to-end (kernel → PyO3 → wrapper marshalling loses nothing).
"""

from __future__ import annotations

import json
import struct
from datetime import date
from pathlib import Path
from typing import Any

import pytest
import trading_core
from brutex.options.greeks import compute_greeks
from brutex.options.risk_free import RISK_FREE_SOURCE_VERSION, RiskFreeRate

FIXTURE_PATH = Path(__file__).parent / "fixtures" / "greeks_golden.json"

_FIELDS = ("iv", "delta", "gamma", "theta", "vega", "rho", "price")


def _load_fixture() -> dict[str, Any]:
    return json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))  # type: ignore[no-any-return]


def _bits(value: float) -> str:
    """Exact IEEE-754 bit pattern of an f64, as 16 lowercase hex chars."""
    return format(struct.unpack("<Q", struct.pack("<d", value))[0], "016x")


def _kernel_outputs(case: dict[str, Any], *, solve: bool) -> tuple[Any, ...]:
    price = case["price"] if solve else None
    sigma = None if solve else case["sigma_true"]
    return tuple(
        trading_core.greeks(
            price,
            sigma,
            case["forward"],
            case["strike"],
            case["t_years"],
            case["rate"],
            case["is_call"],
        )
    )


def _assert_block(case_id: str, path: str, got: tuple[Any, ...], case: dict[str, Any]) -> None:
    frozen = case[f"frozen_{path}_bits"]
    reference = case[f"reference_{path}"]
    fixture = _load_fixture()
    tol_rel = fixture["_meta"]["tolerance"]["rel"]
    tol_abs = fixture["_meta"]["tolerance"]["abs"]
    for name, value in zip(_FIELDS, got[:7], strict=False):
        assert _bits(value) == frozen[name], f"{case_id}/{path}/{name}: bit drift vs frozen wheel"
        want = reference[name]
        allowed = tol_abs + tol_rel * abs(want)
        assert abs(value - want) <= allowed, (
            f"{case_id}/{path}/{name}: mpmath-oracle drift {abs(value - want):e} > {allowed:e}"
        )
    assert bool(got[7]) == frozen["admissible"] == reference["admissible"], (
        f"{case_id}/{path}: admissible drift"
    )


def _case_ids() -> list[str]:
    return [case["id"] for case in _load_fixture()["cases"]]


@pytest.fixture(scope="module")
def cases_by_id() -> dict[str, dict[str, Any]]:
    """All golden cases, keyed by id."""
    return {case["id"]: case for case in _load_fixture()["cases"]}


def test_fixture_is_a_real_matrix() -> None:
    """The golden must keep covering the ATM/ITM/OTM × tenor × side grid."""
    assert len(_case_ids()) >= 20


@pytest.mark.parametrize("case_id", _case_ids())
def test_solve_path_matches_frozen_bits_and_oracle(
    case_id: str, cases_by_id: dict[str, dict[str, Any]]
) -> None:
    """sigma=None: solve IV from the premium, then price — bit-frozen."""
    case = cases_by_id[case_id]
    _assert_block(case_id, "solve", _kernel_outputs(case, solve=True), case)


@pytest.mark.parametrize("case_id", _case_ids())
def test_sigma_path_matches_frozen_bits_and_oracle(
    case_id: str, cases_by_id: dict[str, dict[str, Any]]
) -> None:
    """sigma=Some: price directly off the supplied volatility — bit-frozen."""
    case = cases_by_id[case_id]
    _assert_block(case_id, "sigma", _kernel_outputs(case, solve=False), case)


@pytest.mark.parametrize("case_id", _case_ids())
def test_wrapper_reproduces_the_frozen_bits_end_to_end(
    case_id: str, cases_by_id: dict[str, dict[str, Any]]
) -> None:
    """`brutex.options.greeks.compute_greeks` loses nothing in marshalling."""
    case = cases_by_id[case_id]
    rate = RiskFreeRate(rate=case["rate"], source="fixed", version=RISK_FREE_SOURCE_VERSION)
    out = compute_greeks(
        price=case["price"],
        forward=case["forward"],
        strike=case["strike"],
        t_years=case["t_years"],
        rate=rate,
        is_call=case["is_call"],
    )
    assert out is not None, f"{case_id}: every golden case must solve"
    frozen = case["frozen_solve_bits"]
    values = (out.iv, out.delta, out.gamma, out.theta, out.vega, out.rho, out.price)
    for name, value in zip(_FIELDS, values, strict=False):
        assert _bits(value) == frozen[name], f"{case_id}/wrapper/{name}: bit drift"
    assert out.admissible == frozen["admissible"]
    assert out.rate_source == "fixed"


def test_rate_seam_date_independence(cases_by_id: dict[str, dict[str, Any]]) -> None:
    """A FixedRateSource-derived stamp on any date matches the fixture rate."""
    from brutex.options.risk_free import FixedRateSource

    case = cases_by_id["nifty_atm_call_30d"]
    stamped = FixedRateSource(rate=case["rate"]).rate_on(date(2026, 7, 2))
    assert stamped.rate == case["rate"]
