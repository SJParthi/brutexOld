"""Shared case-enumeration harness for the auto-pull predicate goldens (DEC-RUST-PULL-STATE-001, Wave 3G).

Imported by BOTH ``generate_auto_pull_golden.py`` (the one-shot freeze) and
``test_auto_pull_golden.py`` (the recompute-and-compare gate) — the
``_pull_intent_harness`` shape, never generator-imports-test.

ONE table is computed from the LIVE ``brutex.dashboard.auto_pull``: the
:func:`should_reload_instrument_master` five-input predicate over count
classes (empty lake · indices-missing · stocks-missing · populated · a
defensive negative · an out-of-i64 CPython int) × the exhaustive ``2**3``
flag lattice.  Out-of-i64 counts are ``kernel_row=False`` — the seam keeps
them on the DOCUMENTED Python arm (a representability fact, not a kernel
fault; the intent ``_U64_MAX`` precedent).

The kernel TSV projects the SAME rows onto the dependency-free line format
the crate's own ``cargo test`` replays (the cross-language pin).
"""

from __future__ import annotations

from itertools import product
from typing import Any

from brutex.dashboard.auto_pull import should_reload_instrument_master

_I64_MIN = -(2**63)
_I64_MAX = 2**63 - 1

#: (name-stem, index_count, stock_count) — the count classes.
_COUNT_CLASSES: tuple[tuple[str, int, int], ...] = (
    ("empty", 0, 0),
    ("indices_missing", 0, 5),
    ("stocks_missing", 3, 0),
    ("populated", 3, 5),
    ("negative_defensive", -2, 7),
    ("huge_counts", 2**70, 2**70),
)


def compute_payload() -> dict[str, Any]:
    """The canonical golden payload — recomputed from the LIVE module."""
    rows: list[dict[str, Any]] = []
    for (stem, index_count, stock_count), (legs, econ, elig) in product(
        _COUNT_CLASSES, product((False, True), repeat=3)
    ):
        verdict = should_reload_instrument_master(
            index_count=index_count,
            stock_count=stock_count,
            legs_present=legs,
            stale_economics=econ,
            stale_eligibility=elig,
        )
        rows.append(
            {
                "name": f"{stem}_l{int(legs)}e{int(econ)}g{int(elig)}",
                "index_count": index_count,
                "stock_count": stock_count,
                "legs_present": legs,
                "stale_economics": econ,
                "stale_eligibility": elig,
                "kernel_row": _I64_MIN <= index_count <= _I64_MAX
                and _I64_MIN <= stock_count <= _I64_MAX,
                "verdict": verdict,
            }
        )
    return {"rows": rows}


def compute_tsv(payload: dict[str, Any]) -> str:
    """The serde-free kernel-case projection for the cargo fixture test."""
    lines = ["# generated by tests/golden/generate_auto_pull_golden.py — do not hand-edit"]
    for row in payload["rows"]:
        if not row["kernel_row"]:
            continue
        lines.append(
            "\t".join(
                (
                    "reload",
                    row["name"],
                    str(row["index_count"]),
                    str(row["stock_count"]),
                    str(int(row["legs_present"])),
                    str(int(row["stale_economics"])),
                    str(int(row["stale_eligibility"])),
                    str(int(row["verdict"])),
                )
            )
        )
    return "\n".join(lines) + "\n"
