"""Golden byte-equality oracle for :mod:`brutex.metrics.spa`.

A small, hand-fixed 8x3 excess-return matrix with one clear winner
(column 0), one neutral strategy (column 1) and one loser (column 2),
run through both bootstrap schemes under a pinned seed. The recorded
outputs lock the bootstrap p-values bit-for-bit (Golden Rule #4 — same
input + same seed ⇒ same p-values) and guard against any silent change
to the studentization, recentring, or step-down logic.

Fixture column means: ``[0.9875, 0.05, -0.1625]``.

p-values are integer ``count / n_resamples`` ratios, so the literal
round-trips exactly and is asserted with ``==``. The studentized test
statistics are full-precision floats from ``sqrt``/division and are
asserted to a tight absolute tolerance (exact in this environment; the
tolerance only absorbs sub-ULP float-reduction drift across NumPy
builds — any real regression moves them by far more).

Honest envelope: the p-values were generated by this implementation, not
taken from an external table — they verify *self-consistency and
determinism*, not correctness against a third-party oracle. Correctness
against the literature is argued in the module docstring + the
distributional property tests.
"""

from __future__ import annotations

import numpy as np
import pytest
from brutex.metrics.spa import (
    BootstrapConfig,
    BootstrapMethod,
    hansen_spa,
    reality_check,
    romano_wolf,
)

_DATA = np.array(
    [
        [1.2, -0.3, 0.4],
        [0.8, 0.5, -0.6],
        [1.5, -0.1, -0.2],
        [0.3, 0.2, 0.1],
        [1.1, -0.4, -0.5],
        [0.9, 0.6, -0.3],
        [1.4, -0.2, 0.2],
        [0.7, 0.1, -0.4],
    ]
)
_SEED = 20240603
_RESAMPLES = 5000


def test_golden_stationary() -> None:
    cfg = BootstrapConfig(seed=_SEED, n_resamples=_RESAMPLES, method=BootstrapMethod.STATIONARY)

    rc = reality_check(_DATA, cfg)
    assert rc.pvalue == 0.0
    assert rc.test_statistic == pytest.approx(2.7930717856868634, rel=1e-9, abs=1e-9)
    assert rc.best_strategy == 0
    assert rc.block_length == 3.0
    assert rc.method == "stationary"

    spa = hansen_spa(_DATA, cfg)
    assert spa.pvalue_consistent == 0.0
    assert spa.pvalue_lower == 0.0
    assert spa.pvalue_upper == 0.0
    assert spa.test_statistic == pytest.approx(13.211404300149086, rel=1e-9, abs=1e-9)

    rw = romano_wolf(_DATA, cfg, alpha=0.05)
    assert rw.adjusted_pvalues == (0.0, 0.4124, 0.9858)
    assert rw.naive_pvalues == (0.0, 0.2206, 0.9858)
    assert rw.test_statistics == pytest.approx(
        (13.211404300149086, 0.7338745411292539, -2.2765294879110853), rel=1e-9, abs=1e-9
    )
    assert rw.rejected_indices == (0,)


def test_golden_circular() -> None:
    cfg = BootstrapConfig(seed=_SEED, n_resamples=_RESAMPLES, method=BootstrapMethod.CIRCULAR)

    rc = reality_check(_DATA, cfg)
    assert rc.pvalue == 0.0
    assert rc.test_statistic == pytest.approx(2.7930717856868634, rel=1e-9, abs=1e-9)
    assert rc.method == "circular"

    spa = hansen_spa(_DATA, cfg)
    assert spa.pvalue_consistent == 0.0
    assert spa.pvalue_upper == 0.0
    assert spa.test_statistic == pytest.approx(12.760538799312522, rel=1e-9, abs=1e-9)

    rw = romano_wolf(_DATA, cfg, alpha=0.05)
    assert rw.adjusted_pvalues == (0.0, 0.4438, 1.0)
    assert rw.naive_pvalues == (0.0, 0.2644, 1.0)
    assert rw.rejected_indices == (0,)


def test_golden_determinism_bit_for_bit() -> None:
    """The strongest determinism lock: two independent runs are identical."""
    cfg = BootstrapConfig(seed=_SEED, n_resamples=_RESAMPLES)
    assert reality_check(_DATA, cfg) == reality_check(_DATA, cfg)
    assert hansen_spa(_DATA, cfg) == hansen_spa(_DATA, cfg)
    assert romano_wolf(_DATA, cfg) == romano_wolf(_DATA, cfg)
