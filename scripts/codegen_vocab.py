#!/usr/bin/env python3
"""Codegen the shared condition-vocabulary bit layout from the ONE manifest.

DEC-VOCAB-U128-CODEGEN-001 (ADR-0012 D7). The condition bit LAYOUT lives in
exactly ONE place — ``rust/trading-core/conditions.toml`` — and this single
generator emits BOTH language artifacts from it:

* **Rust** ``rust/trading-core/src/bits.rs`` — ``pub const BIT_*: u32``,
  ``TOTAL_CONDITIONS``, ``MASK_WIDTH``, ``IMPLEMENTED_MASK`` + the in-file
  dense-range test.
* **Python** ``brutex/vocabulary/bits.py`` — ``BIT_*: Final[int]``,
  ``NAME_TO_BIT`` / ``BIT_TO_NAME``, ``GROUP_RANGES``, ``TOTAL_CONDITIONS``,
  ``MASK_WIDTH``, ``ALL_CONDITION_NAMES``, ``IMPLEMENTED_MASK``,
  ``APPLIES_TO_1DAY_MASK`` + the import-time invariant check.

ONE generator emitting both halves is the CLAUDE.md §11 COMMON / zero-duplication
discipline: a ``build.rs`` would only naturally produce the Rust half, forcing a
second Python emitter (two generators). The evaluator *boolean branches* stay
hand-written — codegen owns the bit LAYOUT, not the per-condition math.

Usage::

    python scripts/codegen_vocab.py           # (re)write both artifacts
    python scripts/codegen_vocab.py --check    # CI: regenerate to memory, diff,
                                               # exit 1 on drift (no write)

The ``--check`` mode is the "generated files are up-to-date" CI gate: it renders
both artifacts from the manifest and compares byte-for-byte against the committed
files, failing with a clear "run scripts/codegen_vocab.py" message on any drift.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

#: Repo root (this script lives in ``<root>/scripts``).
ROOT = Path(__file__).resolve().parents[1]
#: The single source of truth.
MANIFEST = ROOT / "rust" / "trading-core" / "conditions.toml"
#: Generated Rust bit layout.
RUST_BITS = ROOT / "rust" / "trading-core" / "src" / "bits.rs"
#: Generated Python bit layout.
PY_BITS = ROOT / "brutex" / "vocabulary" / "bits.py"

#: Header stamped on every generated file (the "do not edit" contract).
_GEN_BANNER_RS = (
    "// @generated by scripts/codegen_vocab.py from rust/trading-core/conditions.toml\n"
    "// DO NOT EDIT BY HAND. Edit the manifest + re-run the generator instead.\n"
    "// DEC-VOCAB-U128-CODEGEN-001 (ADR-0012 D7).\n"
)
_GEN_BANNER_PY = (
    "# @generated by scripts/codegen_vocab.py from rust/trading-core/conditions.toml\n"
    "# DO NOT EDIT BY HAND. Edit the manifest + re-run the generator instead.\n"
    "# DEC-VOCAB-U128-CODEGEN-001 (ADR-0012 D7).\n"
)


@dataclass(frozen=True)
class Condition:
    """One vocabulary condition as declared in the manifest."""

    bit: int
    name: str
    group: str
    description: str
    reserved: bool
    applies_to_1day: bool
    implemented: bool


@dataclass(frozen=True)
class Manifest:
    """The parsed + validated manifest."""

    schema_version: int
    mask_width: int
    conditions: tuple[Condition, ...]

    @property
    def total_conditions(self) -> int:
        """The number of declared condition bits (dense ``0..total-1``)."""
        return len(self.conditions)

    @property
    def implemented_mask(self) -> int:
        """Bitmask of the bits whose evaluator computes a real boolean."""
        return sum(1 << c.bit for c in self.conditions if c.implemented)

    @property
    def applies_1day_mask(self) -> int:
        """Bitmask of the bits valid on the 1day timeframe (ADR-0012 D12)."""
        return sum(1 << c.bit for c in self.conditions if c.applies_to_1day)


class ManifestError(Exception):
    """Raised when the manifest violates an invariant (dense bits, dup name…)."""


def load_manifest(path: Path = MANIFEST) -> Manifest:
    """Parse + validate the manifest TOML into a :class:`Manifest`.

    Raises:
        ManifestError: if ``mask_width`` is not 128, bit positions are not a
            dense ``0..total-1`` range, a bit/name is duplicated, or a group's
            bits are not contiguous.
    """
    raw = tomllib.loads(path.read_text(encoding="utf-8"))
    mask_width = int(raw["mask_width"])
    if mask_width != 128:
        raise ManifestError(f"mask_width must be 128, got {mask_width}")
    conditions = tuple(
        Condition(
            bit=int(c["bit"]),
            name=str(c["name"]),
            group=str(c["group"]),
            description=str(c["description"]),
            reserved=bool(c.get("reserved", False)),
            applies_to_1day=bool(c["applies_to_1day"]),
            implemented=bool(c["implemented"]),
        )
        for c in raw["condition"]
    )
    _validate_manifest(conditions, mask_width)
    return Manifest(
        schema_version=int(raw["schema_version"]),
        mask_width=mask_width,
        conditions=conditions,
    )


def _validate_manifest(conditions: tuple[Condition, ...], mask_width: int) -> None:
    """Validate the manifest invariants (extracted so tests can drive each raise)."""
    bits = [c.bit for c in conditions]
    if sorted(bits) != list(range(len(conditions))):
        raise ManifestError(
            f"condition bits must be a dense 0..{len(conditions) - 1} range, got {sorted(bits)}"
        )
    names = [c.name for c in conditions]
    if len(set(names)) != len(names):
        dupes = sorted({n for n in names if names.count(n) > 1})
        raise ManifestError(f"duplicate condition name(s): {dupes}")
    for c in conditions:
        if c.bit >= mask_width:
            raise ManifestError(f"bit {c.bit} ({c.name}) exceeds mask_width {mask_width}")
    # Each group must occupy a contiguous bit range (so GROUP_RANGES is a clean
    # partition). Groups appear in declaration order; their bits must be a run.
    seen_groups: list[str] = []
    for c in conditions:
        if c.group not in seen_groups:
            seen_groups.append(c.group)
    for group in seen_groups:
        gbits = sorted(c.bit for c in conditions if c.group == group)
        if gbits != list(range(gbits[0], gbits[0] + len(gbits))):
            raise ManifestError(f"group {group!r} bits are not contiguous: {gbits}")


def _group_ranges(manifest: Manifest) -> list[tuple[str, int, int]]:
    """Return ``(group, start, stop)`` half-open ranges in declaration order."""
    ordered: list[str] = []
    for c in manifest.conditions:
        if c.group not in ordered:
            ordered.append(c.group)
    out: list[tuple[str, int, int]] = []
    for group in ordered:
        gbits = sorted(c.bit for c in manifest.conditions if c.group == group)
        out.append((group, gbits[0], gbits[-1] + 1))
    return out


def render_rust(manifest: Manifest) -> str:
    """Render ``bits.rs`` from the manifest."""
    lines: list[str] = [_GEN_BANNER_RS]
    lines.append("//! Bit-position constants for the shared condition vocabulary.")
    lines.append("//!")
    lines.append("//! A bit-for-bit twin of `brutex/vocabulary/bits.py` (both generated from")
    lines.append("//! `conditions.toml`). The strategy mask is a u128 (DEC-VOCAB-U128-CODEGEN-001")
    lines.append(f"//! / ADR-0012 D4); bits 0..={manifest.total_conditions - 1} are the live")
    lines.append("//! conditions, the rest are reserved. Never renumber a bit (grow-only,")
    lines.append("//! DEC-PLUGIN-001).")
    lines.append("")
    cur_group: str | None = None
    for c in manifest.conditions:
        if c.group != cur_group:
            cur_group = c.group
            lines.append(f"// {c.group}")
        suffix = "" if c.implemented else "  (LAYOUT ONLY — implemented=false)"
        lines.append(f"/// {c.description}{suffix}")
        lines.append(f"pub const BIT_{c.name.upper()}: u32 = {c.bit};")
    lines.append("")
    lines.append("/// The number of atomic conditions (dense bits 0..=TOTAL-1).")
    lines.append(f"pub const TOTAL_CONDITIONS: u32 = {manifest.total_conditions};")
    lines.append("")
    lines.append("/// The strategy-mask width in bits (u128 — ADR-0012 D4).")
    lines.append(f"pub const MASK_WIDTH: u32 = {manifest.mask_width};")
    lines.append("")
    lines.append("/// Bitmask of the conditions whose evaluator computes a real boolean.")
    lines.append("/// LAYOUT-ONLY bits (`implemented=false` in the manifest) are 0 here and")
    lines.append("/// the evaluator emits 0 for them until a PR supplies the math.")
    lines.append(f"pub const IMPLEMENTED_MASK: u128 = {manifest.implemented_mask};")
    lines.append("")
    lines.append("#[cfg(test)]")
    lines.append("mod tests {")
    lines.append("    use super::*;")
    lines.append("")
    lines.append(f"    /// The {manifest.total_conditions} bit positions must form a dense")
    lines.append(f"    /// 0..={manifest.total_conditions - 1} range, no gaps, no dupes.")
    lines.append("    #[test]")
    lines.append("    fn bit_positions_are_dense() {")
    lines.append("        let all = [")
    for c in manifest.conditions:
        lines.append(f"            BIT_{c.name.upper()},")
    lines.append("        ];")
    lines.append("        assert_eq!(all.len(), TOTAL_CONDITIONS as usize);")
    lines.append("        let mut sorted = all;")
    lines.append("        sorted.sort_unstable();")
    lines.append("        for (i, &b) in sorted.iter().enumerate() {")
    lines.append('            assert_eq!(b, i as u32, "bit positions must be dense");')
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_python(manifest: Manifest) -> str:
    """Render ``bits.py`` from the manifest."""
    ranges = _group_ranges(manifest)
    lines: list[str] = [_GEN_BANNER_PY.rstrip("\n")]
    lines.append('"""Bit-position constants for the shared condition vocabulary.')
    lines.append("")
    lines.append("Generated from ``rust/trading-core/conditions.toml`` — the SINGLE source of")
    lines.append("truth — by ``scripts/codegen_vocab.py`` (DEC-VOCAB-U128-CODEGEN-001). The Rust")
    lines.append("twin ``rust/trading-core/src/bits.rs`` is generated from the same manifest, so")
    lines.append("BruteX (PyO3) and TickVault (native) share an identical bit layout.")
    lines.append("")
    lines.append(
        f"The strategy mask is a u128 (ADR-0012 D4); bits 0..{manifest.total_conditions - 1}"
    )
    lines.append("are the live conditions. Never renumber a bit (grow-only, DEC-PLUGIN-001):")
    lines.append("new conditions append at the next free bit. LAYOUT-ONLY bits")
    lines.append("(``implemented=false`` in the manifest) declare a position but the evaluator")
    lines.append("emits 0 for them until a later PR supplies the math.")
    lines.append('"""')
    lines.append("")
    lines.append("from __future__ import annotations")
    lines.append("")
    lines.append("from typing import Final")
    lines.append("")
    # Public API surface (``__all__``) — every BIT_* plus the metadata constants
    # and tables, so the codegen-emitted masks (IMPLEMENTED_MASK /
    # APPLIES_TO_1DAY_MASK) are a declared part of the module's public surface for
    # downstream (PR-2) consumption, not flagged as unused module-level globals.
    all_names: list[str] = [f"BIT_{c.name.upper()}" for c in manifest.conditions]
    all_names += [
        "ALL_CONDITION_NAMES",
        "APPLIES_TO_1DAY_MASK",
        "BIT_TO_NAME",
        "GROUP_RANGES",
        "IMPLEMENTED_MASK",
        "MASK_WIDTH",
        "NAME_TO_BIT",
        "TOTAL_CONDITIONS",
    ]
    lines.append("__all__ = [")
    for name in sorted(all_names):
        lines.append(f'    "{name}",')
    lines.append("]")
    lines.append("")
    cur_group: str | None = None
    for c in manifest.conditions:
        if c.group != cur_group:
            cur_group = c.group
            lines.append(f"# ────── {c.group} ──────")
        lines.append(f"BIT_{c.name.upper()}: Final[int] = {c.bit}")
    lines.append("")
    lines.append("# ────── Metadata ──────")
    lines.append(f"TOTAL_CONDITIONS: Final[int] = {manifest.total_conditions}")
    lines.append("#: The strategy-mask width in bits (u128 — ADR-0012 D4).")
    lines.append(f"MASK_WIDTH: Final[int] = {manifest.mask_width}")
    lines.append("")
    lines.append("#: Bitmask of conditions whose evaluator computes a real boolean. LAYOUT-ONLY")
    lines.append("#: bits (``implemented=false``) are 0 here; the evaluator emits 0 for them.")
    lines.append(f"IMPLEMENTED_MASK: Final[int] = {manifest.implemented_mask}")
    lines.append("")
    lines.append("#: Bitmask of conditions valid on the 1day timeframe (ADR-0012 D12). Relative")
    lines.append("#: to ``IMPLEMENTED_MASK`` it clears the SIX intraday-only bits: the four")
    lines.append("#: Time-of-Day bits 44-47 (``BIT_EARLY_MORNING`` / ``BIT_MID_MORNING`` /")
    lines.append("#: ``BIT_MIDDAY`` / ``BIT_AFTERNOON`` — a 1day bar has no time-of-day bucket)")
    lines.append("#: AND the two VWAP-position bits 52-53 (``BIT_CLOSE_ABOVE_VWAP`` /")
    lines.append("#: ``BIT_CLOSE_BELOW_VWAP`` — the session-anchored VWAP is intraday-only).")
    lines.append("#: Test-pinned exactly in ``tests/unit/test_vocabulary.py``.")
    lines.append(f"APPLIES_TO_1DAY_MASK: Final[int] = {manifest.applies_1day_mask}")
    lines.append("")
    lines.append("NAME_TO_BIT: Final[dict[str, int]] = {")
    for c in manifest.conditions:
        lines.append(f'    "{c.name}": BIT_{c.name.upper()},')
    lines.append("}")
    lines.append("")
    lines.append("BIT_TO_NAME: Final[dict[int, str]] = {v: k for k, v in NAME_TO_BIT.items()}")
    lines.append("")
    lines.append("#: Re-exported via the vocabulary package for downstream tooling.")
    lines.append("ALL_CONDITION_NAMES: Final[tuple[str, ...]] = tuple(NAME_TO_BIT.keys())")
    lines.append("")
    lines.append("#: The indicator families and their contiguous half-open bit ranges — the ONE")
    lines.append("#: place the family→bit-range correspondence lives (CLAUDE.md §11 COMMON).")
    lines.append("GROUP_RANGES: Final[tuple[tuple[str, range], ...]] = (")
    for group, start, stop in ranges:
        lines.append(f'    ("{group}", range({start}, {stop})),')
    lines.append(")")
    lines.append("")
    lines.append("")
    lines.append("def _check_invariants(name_to_bit: dict[str, int], total: int) -> None:")
    lines.append('    """Validate the bit-table invariants at module import.')
    lines.append("")
    lines.append("    Extracted so the two ``raise`` branches are reachable from tests (call with")
    lines.append("    a tampered mapping).")
    lines.append("")
    lines.append("    Raises:")
    lines.append("        AssertionError: when the mapping has the wrong count, or when the bit")
    lines.append("        positions do not form a dense ``0..total-1`` range.")
    lines.append('    """')
    lines.append("    if len(name_to_bit) != total:")
    lines.append(
        '        raise AssertionError(f"Expected {total} conditions, got {len(name_to_bit)}")'
    )
    lines.append("    if set(name_to_bit.values()) != set(range(total)):")
    lines.append("        raise AssertionError(")
    lines.append('            f"Bit positions must be 0..{total - 1} with no gaps, "')
    lines.append('            f"got {sorted(name_to_bit.values())}"')
    lines.append("        )")
    lines.append("")
    lines.append("")
    lines.append("# Import-time invariant.")
    lines.append("_check_invariants(NAME_TO_BIT, TOTAL_CONDITIONS)")
    # First apply ruff's lint autofixes (notably RUF022 — isort-style ``__all__``
    # sorting, whose natural-sort order differs from a plain ``sorted()``), THEN
    # ``ruff format``, so the generated file passes BOTH ``ruff check brutex`` and
    # ``ruff format --check brutex`` (ONE formatter+linter authority — the
    # generated file never trips either gate). ruff is a dev dep (CLAUDE.md §4).
    return _ruff_format(_ruff_check_fix("\n".join(lines) + "\n"))


def _ruff_format(source: str) -> str:
    """Format Python *source* with ``ruff format`` (stdin → stdout).

    Run as ``<python> -m ruff format -`` so the generated ``bits.py`` is exactly
    what ``ruff format --check brutex`` produces (CLAUDE.md §4). Raises on a ruff
    failure (a missing ruff is a real environment error, surfaced not hidden).
    """
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout


def _ruff_check_fix(source: str) -> str:
    """Apply ``ruff check --fix`` autofixes to *source* (stdin → fixed stdout).

    Run as ``<python> -m ruff check --fix --exit-zero -`` so the generated
    ``bits.py`` carries ruff's lint autofixes — notably RUF022's isort-style
    ``__all__`` natural sort, which differs from a plain ``sorted()`` (e.g.
    ``BIT_NEAR_FIB_0`` < ``BIT_NEAR_FIB_100`` < ``BIT_NEAR_FIB_200``). ``--exit-zero``
    means "fixed remaining issues are not an error exit"; a genuine ruff/env
    failure still raises (surfaced, not hidden). The ``-`` filename defaults to
    ``.py`` so project lint config applies.
    """
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "check", "--fix", "--exit-zero", "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout


def write_artifacts(manifest: Manifest) -> None:
    """Render + write both artifacts to disk."""
    RUST_BITS.write_text(render_rust(manifest), encoding="utf-8")
    PY_BITS.write_text(render_python(manifest), encoding="utf-8")


def check_artifacts(manifest: Manifest) -> list[str]:
    """Return a list of drift descriptions (empty = up-to-date)."""
    drift: list[str] = []
    for path, rendered in ((RUST_BITS, render_rust(manifest)), (PY_BITS, render_python(manifest))):
        on_disk = path.read_text(encoding="utf-8") if path.exists() else ""
        if on_disk != rendered:
            drift.append(str(path.relative_to(ROOT)))
    return drift


def main(argv: list[str] | None = None) -> int:
    """CLI entry point. ``--check`` diffs, otherwise (re)writes."""
    parser = argparse.ArgumentParser(description="Codegen the vocabulary bit layout.")
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate to memory + diff against committed files; exit 1 on drift",
    )
    args = parser.parse_args(argv)
    manifest = load_manifest()
    if args.check:
        drift = check_artifacts(manifest)
        if drift:
            sys.stderr.write(
                "vocab codegen is STALE — these files do not match the manifest:\n  "
                + "\n  ".join(drift)
                + "\nRun `python scripts/codegen_vocab.py` and commit.\n"
            )
            return 1
        sys.stdout.write("vocab codegen up-to-date.\n")
        return 0
    write_artifacts(manifest)
    sys.stdout.write(
        f"wrote {RUST_BITS.relative_to(ROOT)} + {PY_BITS.relative_to(ROOT)} "
        f"({manifest.total_conditions} conditions, mask_width={manifest.mask_width})\n"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
