"""Pure plist/cron renderers — the single source of truth for the templates.

DEC-BACKUP-OFFBOX-001 (§9): the three launchd templates under
``docs/runbooks/backup-templates/`` are GENERATED from these renderers and
golden-pinned byte-equal, so the docs copies can never drift. Pure string
builders — no I/O, no ``launchctl`` (install stays a manual runbook/ADR-0017
M4 step; §15 R8).

Template law (mirrors the shipped supervisor template's own rules):

* all three jobs are ONE-SHOT — NO ``KeepAlive``, which spin-loops a one-shot;
* ``{{PLACEHOLDER}}`` style + NO secrets in plists: the restic password rides
  ``BRUTEX_BACKUP_PASSWORD_FILE`` (a 0600 path) or ``_COMMAND``; S3/B2 creds
  ride ``~/.brutex/.env``, loaded by ``bootstrap_env()`` at CLI dispatch;
* the dead-man plist deliberately carries NO repo env — the shallow check
  must keep working when the backup env itself is broken.

Fire times (box TZ pinned Asia/Kolkata): nightly run 03:35 (after the 02:30
sweep-daemon default, before the ~06:05 IST token-minter window); hourly
check; monthly drill Day 1 13:00 — deliberately OUTSIDE the nightly run's
own §5 envelope (round-6 MAJOR: 03:35 + the default ``auto`` read-data
subset ≈ 143 GB/night at the runbook's ~100 Mbit/s WAN ≈ 3.2 h ⇒ the run
holds the single-flight lock to ~07:00+, so the previous Day-1 04:30 fire
made the drill's busy skip the deterministic monthly NORM, not an
exception — and launchd one-shots never retry).
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Final

from brutex.backup import backup_rust

if TYPE_CHECKING:
    from collections.abc import Callable
    from types import ModuleType

_GENERATED_NOTE: Final[str] = (
    "     GENERATED by brutex/backup/schedule_render.py — edit the renderer, not this file\n"
    "     (a golden test pins byte-equality). Replace every {{PLACEHOLDER}}; NO secrets here:\n"
    "     the restic password rides BRUTEX_BACKUP_PASSWORD_FILE (0600) or _COMMAND; S3/B2 creds\n"
    "     ride ~/.brutex/.env, loaded by bootstrap_env() at dispatch."
)

#: Inline note above the password-FILE env key (backup + drill plists): the
#: runbook's RECOMMENDED keychain route sets ``BRUTEX_BACKUP_PASSWORD_COMMAND``
#: in ``~/.brutex/.env`` — a non-blank FILE value here would combine with it
#: into the ambiguous-source EXIT_CONFIG refusal every night (F6).
_KEYCHAIN_ROUTE_NOTE: Final[str] = (
    "    <!-- keychain _COMMAND route (runbook step 4): set the value below to an EMPTY\n"
    "         string (blank reads as unset) or delete this key — never leave the literal\n"
    "         placeholder: any non-blank value alongside the .env _COMMAND is the\n"
    "         ambiguous-source EXIT_CONFIG refusal (F6). -->"
)

#: Inline note above the healthcheck-URL env key (dead-man plist): the ping
#: URL does not exist until the healthchecks.io check is created (runbook
#: step 10 / ADR-0017 M6) — AFTER the step-7 plist fill — and launchd env
#: OVERRIDES ``~/.brutex/.env`` (``bootstrap_env`` never overrides an
#: already-set var), so a stale value here silently wins over a later .env
#: edit.
_HEALTHCHECK_URL_NOTE: Final[str] = (
    "    <!-- fill AFTER the healthchecks.io check exists (runbook step 10 / M6); until\n"
    "         then set the value below to an EMPTY string (blank reads as unset) — never\n"
    "         leave the literal placeholder (any non-http(s) value is refused with a WARN\n"
    "         every tick while `backup status` reads SET). The hourly checker reads THIS\n"
    "         value: launchd env OVERRIDES ~/.brutex/.env, so set the URL here and\n"
    "         bootout+bootstrap the agent. A .env-only URL works only if this key is\n"
    "         DELETED — a blank value here still reaches the checker as a PRESENT (empty)\n"
    "         env var, and bootstrap_env never overrides a present var (blank included),\n"
    "         so blank keeps the ping lane OFF while a shell-run `backup status` (no\n"
    "         launchd env) reads SET. -->"
)


