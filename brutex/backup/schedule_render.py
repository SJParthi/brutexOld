# ── The BRUTEX_BACKUP_RUST render seam (DEC-BACKUP-RUST-OPS-001) ──────────
#
# Each public renderer routes through the ``brutex_ops`` crate twin when the
# default-ON flag is ON (the golden plists under
# ``docs/runbooks/backup-templates/`` are the cross-language byte pin — the
# cargo suite pins Rust == golden, the Python golden suite pins Python ==
# golden, and the seam's burn-in byte-compares Rust == Python per call).
# Flag OFF serves the verbatim ``_render_*_python`` oracle, crate untouched.


def _str_thunk(value: object) -> Callable[[], str]:
    """Refuse-poison thunk: a non-``str`` crate render is refused (oracle served)."""

    def _materialise() -> str:
        if not isinstance(value, str):
            raise TypeError(f"crate render returned {type(value).__name__}, expected str")
        return value

    return _materialise


def _routed_render(law: str, oracle: Callable[[], str]) -> str:
    """Route one renderer through the seam (ONE shape for all four)."""

    def _compute(crate: ModuleType) -> object:
        return _str_thunk(getattr(crate, law)())

    return backup_rust.route_law(law, oracle=oracle, compute=_compute)


def render_backup_plist() -> str:
    """Render the nightly backup LaunchAgent template (03:35 IST, one-shot)."""
    return _routed_render("render_backup_plist", _render_backup_plist_python)


def render_deadman_plist() -> str:
    """Render the hourly dead-man checker LaunchAgent template (NO repo env)."""
